import Foundation

/// The pasteboard types the history stores, as UTI strings. Everything else
/// on the pasteboard (web archives, app-private data) is ignored.
public enum ClipType {
    public static let fileURL = "public.file-url"
    public static let png = "public.png"
    public static let tiff = "public.tiff"
    public static let rtf = "public.rtf"
    public static let flatRTFD = "com.apple.flat-rtfd"
    public static let html = "public.html"
    public static let plainText = "public.utf8-plain-text"

    /// Stored types in the order they are written back to the pasteboard.
    public static let stored: [String] = [fileURL, png, tiff, flatRTFD, rtf, html, plainText]

    public static let images: Set<String> = [png, tiff]
}

/// How password managers and similar apps mark pasteboard content
/// (<http://nspasteboard.org>). The history records these items anyway and
/// only uses the markers to flag them as sensitive.
public enum SensitivityRules {
    public static let markerTypes: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword",
    ]

    /// Apps whose every copy counts as sensitive, marker or not.
    public static let passwordManagers: Set<String> = [
        "com.1password.1password",
        "com.agilebits.onepassword7",
        "com.apple.Passwords",
        "com.apple.keychainaccess",
        "com.bitwarden.desktop",
        "org.keepassxc.keepassxc",
        "com.lastpass.LastPass",
        "in.sinew.Enpass-Desktop",
        "com.dashlane.dashlanephonefinal",
        "me.proton.pass.electron",
    ]

    public static func isSensitive(types: some Sequence<String>, sourceBundleID: String?) -> Bool {
        if let sourceBundleID, passwordManagers.contains(sourceBundleID) { return true }
        return types.contains { markerTypes.contains($0) }
    }
}
